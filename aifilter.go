package main

import (
	"regexp"
	"strings"

	"github.com/gin-gonic/gin"
)

// Pinterest doesn't expose an "AI generated" flag to logged-out clients, so
// the "Hide AI art" filter only catches pins that say so themselves in their
// title, description, hashtags or keywords.

const (
	hideAIKey    = "hide_ai"
	hideAIMaxAge = 60 * 60 * 24 * 365
)

var aiArtPattern = regexp.MustCompile(`(?i)` +
	// "AI generated", "A.I art", "ai-created", ...
	`\ba\.?i\.?[\s-]+(?:generated|art|artwork|image|images|created|made|illustration|painting|prompt|prompts|model|portrait|photography|render|rendered|girl|anime|wallpaper)\b` +
	// "generated by AI", "made with Midjourney", ...
	`|\b(?:generated|created|made|rendered|drawn)\s+(?:by|with|using)\s+(?:an?\s+)?(?:a\.?i\.?|artificial intelligence|midjourney|stable\s?diffusion|dall-?e)\b` +
	// #aiart, #aigenerated, #ai_art, #aiartwork, ...
	`|#a\.?i_?(?:art|generated|image|girl|anime|illustration|portrait|photography|wallpaper|prompt|created|generative|design|model|render)\w*` +
	`|#generativeai\b` +
	// Common generators.
	`|\bmidjourney\b|\bstable\s?diffusion\b|\bdall-e\b|\bdalle\s?[23]\b|\bnijijourney\b|\bnovelai\b|\bcivitai\b|\bartificial intelligence\b`)

func looksAIGenerated(texts ...string) bool {
	return aiArtPattern.MatchString(strings.Join(texts, "\n"))
}

func (p pinPayload) looksAIGenerated() bool {
	return looksAIGenerated(
		p.title(),
		p.Description,
		strings.Join(p.PinJoin.VisualAnnotation, "\n"),
	)
}

// hideAIPreference reports whether AI art should be hidden. The search form
// sends noai=1 or noai=0, which is remembered in a cookie so it also applies
// to pagination and to related pins.
func hideAIPreference(c *gin.Context) bool {
	if values, ok := c.GetQueryArray("noai"); ok && len(values) > 0 {
		hide := values[len(values)-1] == "1"
		if hide {
			c.SetCookie(hideAIKey, "1", hideAIMaxAge, "/", "", false, true)
		} else {
			clearCookie(c, hideAIKey)
		}
		return hide
	}
	return cookieValue(c, hideAIKey) == "1"
}
